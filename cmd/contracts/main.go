// Command contracts generates frontend API types without importing runtime services.
package main

import (
	"flag"
	"fmt"
	"os"
	"reflect"
	"strings"

	"worktree-hub/internal/apitypes"
)

func main() {
	check := flag.Bool("check", false, "reject generated contract drift")
	flag.Parse()
	var out strings.Builder
	out.WriteString("// Code generated by go run ./cmd/contracts. DO NOT EDIT.\n\n")
	for _, value := range []any{apitypes.TurnSettings{}, apitypes.DirectoryBindingInput{}, apitypes.CreateSessionInput{}, apitypes.APIErrorResponse{}} {
		t := reflect.TypeOf(value)
		fmt.Fprintf(&out, "export interface %s {\n", t.Name())
		for i := 0; i < t.NumField(); i++ {
			field := t.Field(i)
			parts := strings.Split(field.Tag.Get("json"), ",")
			name := parts[0]
			// Go decoders accept omitted request fields as their zero value.
			// Required request_id is enforced by the creation use case.
			optional := "?"
			if t.Name() == "APIErrorResponse" && name == "error" || t.Name() == "CreateSessionInput" && name == "request_id" {
				optional = ""
			}
			fmt.Fprintf(&out, "  %s%s: %s\n", name, optional, tsType(field.Type))
		}
		out.WriteString("}\n\n")
	}
	generated := strings.TrimRight(out.String(), "\n") + "\n"
	const destination = "frontend/api/contracts.ts"
	if *check {
		current, err := os.ReadFile(destination)
		if err != nil || string(current) != generated {
			fmt.Fprintln(os.Stderr, "API contract drift: run npm run api:generate")
			os.Exit(1)
		}
		return
	}
	if err := os.MkdirAll("frontend/api", 0755); err != nil {
		panic(err)
	}
	if err := os.WriteFile(destination, []byte(generated), 0644); err != nil {
		panic(err)
	}
}

func tsType(t reflect.Type) string {
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Slice:
		return tsType(t.Elem()) + "[]"
	case reflect.Struct:
		return t.Name()
	default:
		panic("unsupported contract field: " + t.String())
	}
}
